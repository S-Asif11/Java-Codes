package com.asif.blc;

public class Calculator {
	
	public static int add(int x,int y) {
		int sum = x+y;
		
		return sum;
	}
	
	public static int sub(int x,int y) {
		int minus = x-y;
		return minus;
	}
	
	public static int mul(int x,int y) {
		int multi = x*y;
		return multi;
	}
	
	public static int div(int x,int y) {
		int division = x/y;
		return division;
	}
}


